from __future__ import annotations

import pytest

from sreditor.render import (
    DOCUMENTS,
    describe_rule,
    render_agents,
    render_claude,
    render_readme,
)
from sreditor.store import Statement, StoreSettings
from tests.conftest import STATEMENTS, statement


def load(items: list[dict]) -> list[Statement]:
    return [Statement.model_validate(item) for item in items]


@pytest.fixture
def claude_text(settings: StoreSettings) -> str:
    return render_claude(load(STATEMENTS), settings)


def test_claude_starts_with_generated_header(claude_text: str) -> None:
    assert claude_text.startswith(
        "<!-- Generated by sreditor from the stmt store (domain demo, scope /)."
    )


def test_claude_ends_with_one_newline(claude_text: str) -> None:
    assert claude_text.endswith("\n") and not claude_text.endswith("\n\n")


def test_claude_orders_categories_alphabetically(claude_text: str) -> None:
    assert claude_text.index("## agents") < claude_text.index("## engineering")


def test_claude_leaves_out_readme_prose(claude_text: str) -> None:
    assert "readme" not in claude_text


def test_claude_orders_rules_by_priority(claude_text: str) -> None:
    order = [
        claude_text.index(f"(`{statement_id}`)")
        for statement_id in ("code.api", "code.style", "code.check", "code.review")
    ]
    assert order == sorted(order)


def test_claude_writes_each_rule_as_bullet_with_its_id(claude_text: str) -> None:
    assert "- Use FastAPI. (`code.api`)\n" in claude_text


def test_readme_renders_prose_in_order_then_rules(settings: StoreSettings) -> None:
    text = render_readme(load(STATEMENTS), settings)

    assert "# demo\n\nA generator for documents.\n<!-- readme.10.intro -->" in text
    assert text.index("readme.10.intro") < text.index("readme.20.usage") < text.index("## Rules")
    assert "### engineering" in text


def test_readme_without_rules_has_no_rules_section(settings: StoreSettings) -> None:
    text = render_readme(load([statement("readme.intro", "readme", "Hello.")]), settings)
    assert "## Rules" not in text


@pytest.mark.parametrize(
    ("statement_id", "expected"),
    [
        ("code.api", ""),
        (
            "code.review",
            (
                "Applies when `ctx.branch == 'main'` and `!ctx.reviewed`. "
                "BLOCK on before event `code.write`."
            ),
        ),
        ("code.check", "ACT on after event `code.write`, runs `code.check`."),
    ],
)
def test_describe_rule_statement_returns_expected_description(
    statement_id: str, expected: str
) -> None:
    by_id = {item.id: item for item in load(STATEMENTS)}
    assert describe_rule(by_id[statement_id]) == expected


def test_describe_rule_schedule_without_operation() -> None:
    (scheduled,) = load(
        [
            statement(
                "ops.nightly",
                "ops",
                "Run nightly.",
                rule={"effect": "ACT", "trigger": {"kind": "CRON"}},
            )
        ]
    )
    assert describe_rule(scheduled) == "ACT on cron."


def test_agents_matches_claude_except_title(settings: StoreSettings) -> None:
    statements = load(STATEMENTS)
    agents = render_agents(statements, settings)

    assert "\n\n# AGENTS.md\n\n" in agents
    assert agents.replace("# AGENTS.md", "# CLAUDE.md") == render_claude(statements, settings)


@pytest.mark.parametrize(
    ("name", "path"), [("agents", "AGENTS.md"), ("claude", "CLAUDE.md"), ("readme", "README.md")]
)
def test_documents_registry_maps_document_name_to_path(name: str, path: str) -> None:
    assert DOCUMENTS[name].path == path


def test_documents_registry_lists_exactly_the_known_documents() -> None:
    assert set(DOCUMENTS) == {"agents", "claude", "readme"}


def test_render_legal_prose_is_excluded_from_rules(settings: StoreSettings) -> None:
    statements = load(
        [
            statement("terms.10.intro", "terms", "Terms text."),
            statement("privacy.10.intro", "privacy", "Privacy text."),
            statement("terms.pt-br.10.intro", "terms.pt-br", "Terms text in Portuguese."),
            statement("code.api", "engineering", "Use FastAPI."),
        ]
    )
    for text in (render_claude(statements, settings), render_readme(statements, settings)):
        assert "Use FastAPI." in text
        assert "Terms text." not in text and "Privacy text." not in text
