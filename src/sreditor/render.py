"""Render Markdown documents from the store's statements."""

from __future__ import annotations

from collections.abc import Callable, Iterable, Sequence
from itertools import groupby

from pydantic import BaseModel, ConfigDict

from sreditor.rules_file import RULES_CSV, render_rules_csv
from sreditor.store import Statement, StoreSettings

# Statements in these categories are prose for a document or page, not agent rules.
README_CATEGORY = "readme"
TERMS_CATEGORY = "terms"
PRIVACY_CATEGORY = "privacy"
PROSE_CATEGORIES = frozenset({README_CATEGORY, TERMS_CATEGORY, PRIVACY_CATEGORY})


def is_prose(category: str) -> bool:
    """A prose category, or its translation such as terms.pt-br (rule i18n.prose)."""
    return category.split(".", 1)[0] in PROSE_CATEGORIES


def banner(settings: StoreSettings) -> str:
    """The comment that marks a generated document and says how to change it."""
    return (
        f"<!-- Generated by sreditor from the stmt store "
        f"(domain {settings.domain}, scope {settings.scope}). Do not edit this file: "
        f"revise the statement in the store, then run `sreditor render`. -->"
    )


def _order(statement: Statement) -> tuple[str, int, str]:
    return (statement.category, statement.priority, statement.id)


def describe_rule(statement: Statement) -> str:
    """Spell out a statement's conditions and operational rule, if any."""
    parts: list[str] = []
    if statement.conditionals:
        conditions = " and ".join(f"`{c}`" for c in statement.conditionals)
        parts.append(f"Applies when {conditions}.")
    if statement.rule is not None:
        trigger = statement.rule.trigger
        when = " ".join(p.lower() for p in (trigger.phase, trigger.kind) if p)
        target = f" `{trigger.operation}`" if trigger.operation else ""
        text = f"{statement.rule.effect} on {when}{target}"
        action = (statement.rule.action or {}).get("operation")
        if action:
            text += f", runs `{action}`"
        parts.append(text + ".")
    return " ".join(parts)


def rule_line(statement: Statement) -> str:
    """One rule as a Markdown list item, with its id and any detail about how it is enforced."""
    detail = describe_rule(statement)
    line = f"- {statement.statement} (`{statement.id}`)"
    return f"{line} {detail}" if detail else line


def rule_sections(statements: Iterable[Statement], level: int) -> list[str]:
    """Group rules by category under headings of the given level."""
    rules = sorted((s for s in statements if not is_prose(s.category)), key=_order)
    blocks: list[str] = []
    for category, group in groupby(rules, key=lambda statement: statement.category):
        lines = "\n".join(rule_line(statement) for statement in group)
        blocks.append(f"{'#' * level} {category}\n\n{lines}")
    return blocks


AGENT_INTRO = (
    "Rules for agents working in this repository. Each id names a statement in the "
    "stmt store, the source of truth; read one with `stmt get ID`."
)


def render_agent_rules(title: str, statements: Sequence[Statement], settings: StoreSettings) -> str:
    """Render the rule file an agent loads, under the file name that agent looks for."""
    blocks = [banner(settings), f"# {title}", AGENT_INTRO, *rule_sections(statements, level=2)]
    return "\n\n".join(blocks) + "\n"


def render_claude(statements: Sequence[Statement], settings: StoreSettings) -> str:
    """CLAUDE.md, read by Claude Code."""
    return render_agent_rules("CLAUDE.md", statements, settings)


def render_agents(statements: Sequence[Statement], settings: StoreSettings) -> str:
    """AGENTS.md, the cross-tool convention read by Codex, Cursor, Copilot and others."""
    return render_agent_rules("AGENTS.md", statements, settings)


def render_readme(statements: Sequence[Statement], settings: StoreSettings) -> str:
    """The README: its prose statements, then the rules by category."""
    prose = sorted((s for s in statements if s.category == README_CATEGORY), key=_order)
    blocks = [
        banner(settings),
        f"# {settings.domain}",
        *(f"{s.statement}\n<!-- {s.id} -->" for s in prose),
    ]
    rules = rule_sections(statements, level=3)
    if rules:
        blocks += ["## Rules", *rules]
    return "\n\n".join(blocks) + "\n"


class Document(BaseModel):
    """A generated document: its name, where it is written and how it is rendered."""

    model_config = ConfigDict(frozen=True)

    name: str
    path: str
    render: Callable[[Sequence[Statement], StoreSettings], str]


